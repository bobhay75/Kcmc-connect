<div class="kicker">Sunday Bulletin • The Bible in America — Part 5</div>
<h1>The Book That Went to the World</h1>
<h2>America didn't just receive the Bible — it became one of the great senders of Scripture, missionaries, translators and humanitarian aid.</h2>
<p>From a haystack in Massachusetts to heart-language translation projects around the world, Scripture helped fuel an extraordinary missionary and generosity movement.</p>
</header>

<article class="sheet">
<section class="section">
<h2>1. The Missionary Movement</h2>
<p>Five students sheltering under a <span class="answer">haystack</span> made a covenant around Samuel Mills' conviction: <span class="answer">“We can do it if we will.”</span></p>
<p><span class="year">1812</span> — <span class="answer">Adoniram Judson</span> sails for Asia and ultimately Burma, becoming the best-known pioneer of America's first foreign missionary movement.</p>
<p><span class="year">1886</span> — the <span class="answer">Student Volunteer Movement</span> is born at Mount Hermon. <span class="answer">100 students</span> volunteered at the founding conference, and more than <span class="answer">20,000</span> eventually reached overseas mission fields through the movement.</p>
<p>America became one of the world's <span class="answer">largest</span> missionary-sending nations, though modern rankings vary depending on how “missionary” and “sender” are defined.</p>
</section>

<section class="section">
<h2>2. The Generosity Movement</h2>
<p>World Vision founder Bob Pierce prayed: “Let my heart be <span class="answer">broken</span> by the things that break the heart of God.”</p>
<p>American Bible Society — founded in 1816 — has published and distributed well over <span class="answer">4 billion</span> Bibles and Scripture portions across its history.</p>
<p>American churches and Christian organizations have given <span class="answer">billions of dollars every year</span> to overseas missions, relief and development. Historical estimates vary by study and definition; one major estimate placed U.S. church-supported overseas relief and development above <span class="answer">$13 billion annually</span>.</p>
</section>

<section class="section">
<h2>3. The Bible Translation Movement</h2>
<p>Cameron Townsend was confronted with the question, “Why doesn't God speak my language?” He went on to found <span class="answer">Wycliffe Bible Translators</span>.</p>
<p>His conviction: <span class="answer">every person</span> deserves access to Scripture in the language of their heart.</p>
<p>Today, more than <span class="answer">4,100 languages</span> have at least some Scripture, and Bible translation work is active in more than <span class="answer">4,400 languages</span> worldwide.</p>
</section>

