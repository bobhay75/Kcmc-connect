'use strict';
const fs=require('fs'),path=require('path'),crypto=require('crypto'),assert=require('assert/strict');
const app=path.join(__dirname,'../KCMC-Connect-Phase6-Recreated');
const read=p=>fs.readFileSync(path.join(app,p),'utf8');
const html=read('index.php'),css=read('home-welcome.css'),sw=read('sw.js');
assert.equal(crypto.createHash('sha256').update(fs.readFileSync(path.join(app,'assets/visuals/kcmc-building-original-20261018.jpg'))).digest('hex'),'064cc83e891de756d47c022725be4e7e1fd1d15119a972aee7e1a58e38c6f226','authentic photo must remain byte-for-byte original');
assert(!html.includes('data-hero-gallery'),'no rotating hero');
assert.equal((html.match(/data-authentic-building/g)||[]).length,1);
assert(html.includes('home-welcome.css?v=tony-functions-20261020'));
assert(html.indexOf('home-welcome.css')>html.indexOf('kcmc_screen_assets()'),'new public overrides follow shared theme');
assert(css.includes('#0d2235')&&css.includes('object-fit:contain'));
assert(sw.includes("'./home-welcome.css?v=tony-functions-20261020'")&&sw.includes("'./assets/visuals/kcmc-building-original-20261018.jpg'"));
assert(sw.includes('public-only-tony-functions-20261020')&&sw.includes('credentials:\'omit\''),'refresh anonymous public cache only');
assert(sw.includes("renotify:true")&&sw.includes('!PUBLIC_PATHS.has(url.pathname)'),'retain notification display and cache privacy');
assert(html.includes("kcmc_has_role(['pastor_admin', 'recovery_admin'], $member)"),'retain admin navigation access controls');
assert.equal((html.match(/Called to love and serve\./g)||[]).length,2,'approved mission is visible in welcome identity and footer');
assert(!html.includes('class="church-life-more"'),'landing gallery removed by Tony request');
assert(html.includes('kcmc_worship_services($kcmc)'),'three service cards use the shared service registry');
